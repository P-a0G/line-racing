"""Exports a trained DuelingIQNNet into the plain-numpy weight dict
forward.py consumes, then hands off to weights_codec.py (shared with the
actual submission) to quantize and pack it. Same folding rules as
summer_challenge_2026's export.py: spectral norm's `.weight` is already the
effective normalized weight, ReZero's alpha folds into conv2 by a scalar
multiply, and only NoisyNet's weight_mu/bias_mu ship (sigma/noise are
training-exploration-only).
"""
import numpy as np
import torch

import tron_rl  # noqa: F401  (side effect: puts submission/tron_infer on sys.path)
from tron_rl.net import DuelingIQNNet


def extract_weights(net):
    """net: a DuelingIQNNet (any train/eval mode -- extraction doesn't
    depend on it, though eval() is what makes the torch side comparable to
    this extraction for a parity check, since training-mode NoisyNet noise
    isn't part of what's extracted). Returns a plain nested dict of float32
    numpy arrays, structured exactly as forward.py's `weights` argument
    expects."""
    def w(t):
        return t.detach().cpu().numpy().astype(np.float32)

    blocks = []
    for block in net.trunk.blocks:
        entry = {
            "conv1": w(block.conv1.weight),
            "conv2": w(block.conv2.weight) * float(block.alpha.detach().item()),
        }
        if block.gpb is not None:
            entry["gpb"] = {"weight": w(block.gpb.fc.weight), "bias": w(block.gpb.fc.bias)}
        blocks.append(entry)

    def noisy(layer):
        return {"weight": w(layer.weight_mu), "bias": w(layer.bias_mu)}

    def plain(layer):
        return {"weight": w(layer.weight), "bias": w(layer.bias)}

    return {
        "trunk": {"stem": {"weight": w(net.trunk.stem.weight)}, "blocks": blocks},
        "iqn": plain(net.iqn.fc),
        "value_fc1": noisy(net.value_fc1),
        "value_fc2": noisy(net.value_fc2),
        "adv_fc1": noisy(net.adv_fc1),
        "adv_fc2": noisy(net.adv_fc2),
    }


def export_checkpoint(checkpoint_path, net_kwargs, out_path, codec_name="base64"):
    """Loads a training checkpoint (as saved by train.py), extracts and
    packs its online net, and writes a weights_blob.py module containing the
    encoded literal and a `load()` function -- the artifact
    build_submission.py concatenates into the final submission."""
    from weights_codec import pack  # deferred: weights_codec.py doesn't exist until a later milestone

    ckpt = torch.load(checkpoint_path, map_location="cpu")
    net = DuelingIQNNet(**net_kwargs)
    net.load_state_dict(ckpt["online"])
    net.eval()

    weights = extract_weights(net)
    literal, raw_bytes = pack(weights, codec_name)

    with open(out_path, "w", encoding="utf-8") as f:
        f.write('"""Generated by training/tron_rl/export.py -- do not hand-edit."""\n')
        f.write(f"CODEC = {codec_name!r}\n")
        f.write(f"_BLOB = '{literal}'\n\n")
        f.write("def load():\n")
        f.write("    from weights_codec import unpack\n")
        f.write("    return unpack(_BLOB, CODEC)\n")

    return literal, raw_bytes
