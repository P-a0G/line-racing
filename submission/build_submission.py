"""Assembles the standalone CG submission: concatenates weights_codec.py,
features_core.py, forward.py, weights_blob.py (must already be generated by
training/tron_rl/export.py), and cg_main.py, in dependency order, into one
file with every local `import`/`from X import Y` between them stripped (once
concatenated they share one namespace, so those imports would either fail --
no such module exists standalone -- or shadow real names).

Minification here only strips full-line comments, module/function/class
docstrings, and blank lines -- safe (uses `ast`/`tokenize`, not regex, so it
can't be fooled by a `#` or triple-quote inside an actual string literal),
same approach as summer_challenge_2026's build_submission.py.

Usage: python3 build_submission.py
Writes submission.py next to this script and prints its final character
count (warns loudly if anywhere near CodinGame's ~100k-character cap --
though this network is small enough that should never actually happen).
"""
import argparse
import ast
import io
import sys
import tokenize
from pathlib import Path

HERE = Path(__file__).resolve().parent

# Dependency order: a module only ever depends on ones before it in this list.
LOCAL_MODULES = ["weights_codec", "features_core", "forward"]
LOCAL_NAMES = set(LOCAL_MODULES) | {"weights_blob"}

SAFE_CHAR_BUDGET = 95_000  # headroom under CodinGame's ~100k-char cap


def _strip_comments(source):
    out_tokens = []
    for tok in tokenize.generate_tokens(io.StringIO(source).readline):
        if tok.type == tokenize.COMMENT:
            continue
        out_tokens.append(tok)
    return tokenize.untokenize(out_tokens)


def _strip_docstrings(source):
    tree = ast.parse(source)
    doc_line_ranges = []
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            body = node.body
            if body and isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant) \
                    and isinstance(body[0].value.value, str):
                doc_line_ranges.append((body[0].lineno, body[0].end_lineno))

    if not doc_line_ranges:
        return source
    remove = set()
    for start, end in doc_line_ranges:
        remove.update(range(start, end + 1))
    lines = source.splitlines()
    return "\n".join(line for i, line in enumerate(lines, start=1) if i not in remove)


def _strip_local_imports(source):
    """Drops any `import X`/`from X import ...` line where X is one of this
    build's own local modules (they're being concatenated, not imported)."""
    out = []
    for line in source.splitlines():
        stripped = line.strip()
        words = stripped.split()
        if len(words) >= 2 and words[0] in ("import", "from") and words[1].split(".")[0] in LOCAL_NAMES:
            continue
        out.append(line)
    return "\n".join(out)


def _collapse_blank_lines(source):
    lines = [line for line in source.splitlines() if line.strip()]
    return "\n".join(lines)


def minify(source):
    source = _strip_local_imports(source)
    source = _strip_docstrings(source)
    source = _strip_comments(source)
    source = _collapse_blank_lines(source)
    return source


def build(out_path=None):
    weights_blob_path = HERE / "tron_infer" / "weights_blob.py"
    if not weights_blob_path.exists():
        raise FileNotFoundError(
            f"{weights_blob_path} doesn't exist -- run training/tron_rl/export.py first "
            "(export_checkpoint(...)) to generate it from a trained checkpoint."
        )

    parts = []
    for name in LOCAL_MODULES:
        parts.append(minify((HERE / "tron_infer" / f"{name}.py").read_text(encoding="utf-8")))
    parts.append(minify(weights_blob_path.read_text(encoding="utf-8")))
    parts.append(minify((HERE / "cg_main.py").read_text(encoding="utf-8")))

    assembled = "\n".join(parts) + "\n"
    compile(assembled, "<submission>", "exec")  # fail loudly here, not on CodinGame's judge

    out_path = Path(out_path) if out_path else HERE / "submission.py"
    out_path.write_text(assembled, encoding="utf-8", newline="\n")

    size = len(assembled)
    print(f"wrote {out_path} ({size} chars)")
    if size > SAFE_CHAR_BUDGET:
        print(f"WARNING: {size} chars exceeds the {SAFE_CHAR_BUDGET}-char safety budget "
              f"(CodinGame's cap is ~100,000) -- shrink the network (net.py's channels/blocks).",
              file=sys.stderr)
    return out_path, size


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=str, default=None)
    args = parser.parse_args()
    build(out_path=args.out)
