"""CodinGame stdin/stdout protocol loop for the Tron/lumicycle submission.

Per rules.md: (X0,Y0) is each player's original spawn (constant for the
whole game) and (X1,Y1) is their current head -- the protocol never reports
the intermediate polyline. But every still-alive player moves exactly once
per round and we read stdin exactly once per round (right before our own
turn), so inserting each round's (X0,Y0) and (X1,Y1) into a running
per-player trail set is lossless: X0,Y0 is a no-op after the first time
(it never changes), and X1,Y1 is always exactly the one new cell that
player claimed since we last saw them. A player reporting -1,-1,-1,-1 has
been eliminated -- their trail is dropped so those cells read as free again,
matching the real engine's immediate trail-vanish behavior.
"""
import sys

import numpy as np

from features_core import WIDTH, HEIGHT, build_observation
from forward import forward
from weights_codec import unpack

DIRECTIONS = ["UP", "DOWN", "LEFT", "RIGHT"]
_DELTAS = ((0, -1), (0, 1), (-1, 0), (1, 0))  # matches DIRECTIONS' order and simulator/Engine.hpp's enum
NUM_TAUS = 8
_MIDPOINT_TAUS = np.array([(2 * k - 1) / (2 * NUM_TAUS) for k in range(1, NUM_TAUS + 1)])


def legal_moves(grid_owner, x, y):
    legal = []
    for dx, dy in _DELTAS:
        nx, ny = x + dx, y + dy
        legal.append(0 <= nx < WIDTH and 0 <= ny < HEIGHT and grid_owner[ny, nx] == -1)
    return np.array(legal)


def parse_round(n, player_lines, trails):
    """player_lines: the n raw "x0 y0 x1 y1" input lines for this round, in
    player-id order. Mutates `trails` in place (adds newly-claimed cells,
    drops an eliminated player's trail entirely) and returns (grid_owner,
    heads, alive) -- the contract build_observation()/reward.potential()
    both expect. Kept separate from main()'s I/O loop so it's directly
    testable against a synthetic transcript, without needing real stdin or a
    trained weights blob."""
    heads = [None] * n
    alive = [True] * n
    for i in range(n):
        x0, y0, x1, y1 = map(int, player_lines[i].split())
        if x1 == -1:
            alive[i] = False
            trails.pop(i, None)
            continue
        cells = trails.setdefault(i, set())
        cells.add((x0, y0))
        cells.add((x1, y1))
        heads[i] = (x1, y1)

    grid_owner = np.full((HEIGHT, WIDTH), -1, dtype=np.int8)
    for i, cells in trails.items():
        for (cx, cy) in cells:
            grid_owner[cy, cx] = i
    return grid_owner, heads, alive


def main():
    from weights_blob import load  # generated by export.py; concatenated in by build_submission.py

    weights = load()
    trails = {}         # player id -> set of (x, y) cells claimed so far
    total_moves = 0      # a turn-number proxy (see obs's turn_number channel) -- not exactly
                          # Engine.hpp's move_count, since an elimination's exact mid-round timing
                          # isn't observable from here, but close enough for a normalization feature

    while True:
        line = sys.stdin.readline()
        if not line:
            break
        n, p = map(int, line.split())
        player_lines = [sys.stdin.readline() for _ in range(n)]
        grid_owner, heads, alive = parse_round(n, player_lines, trails)

        total_moves += n
        legal = legal_moves(grid_owner, *heads[p])
        obs = build_observation(grid_owner, heads, alive, p, total_moves)
        out = forward(obs, legal, _MIDPOINT_TAUS, weights)
        action = int(out["q"].mean(axis=0).argmax())
        print(DIRECTIONS[action])
        sys.stdout.flush()


if __name__ == "__main__":
    main()
